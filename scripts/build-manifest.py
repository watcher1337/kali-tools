#!/usr/bin/env python3
"""Build manifest.yaml from the canonical skill tree.

The manifest is generated; edit skills, not the manifest. --check rebuilds in
memory and fails if the committed manifest.yaml is stale (used by tests/CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from catalog_common import (  # noqa: E402
    FrontmatterError,
    LICENSE_ID,
    REPO_ROOT,
    load_catalog,
    parse_frontmatter,
    parse_simple_yaml,
)

CATALOG_VERSION = "0.1.0"
FORMAT_VERSION = 1
SUPPORTED_PLATFORMS = ["generic", "opencode", "claude-code", "codex", "cursor"]

# Platform verification record: version, validation method, result.
# Update when new evidence exists (see adapters/<platform>/README.md).
PLATFORMS: dict[str, dict[str, str]] = {
    "generic": {
        "status": "verified",
        "version": "n/a (plain Markdown distribution)",
        "validation": "structural tests over the generated tree",
        "result": "pass",
    },
    "opencode": {
        "status": "docs-verified",
        "version": "not runtime-tested",
        "validation": "official installation guidance linked from adapters/opencode",
        "result": "runtime test required before release",
    },
    "claude-code": {
        "status": "docs-verified",
        "version": "not runtime-tested",
        "validation": "official installation guidance linked from adapters/claude-code",
        "result": "runtime test required before release",
    },
    "codex": {
        "status": "docs-verified",
        "version": "not runtime-tested",
        "validation": "official installation guidance linked from adapters/codex",
        "result": "runtime test required before release",
    },
    "cursor": {
        "status": "docs-verified",
        "version": "not runtime-tested",
        "validation": "official installation guidance linked from adapters/cursor",
        "result": "runtime test required before release",
    },
}


def q(value: object) -> str:
    """JSON-quote a scalar (valid as a YAML double-quoted scalar)."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(value, ensure_ascii=False)


def qlist(values: list) -> str:
    return "[" + ", ".join(q(v) for v in values) + "]"


def build(root: Path | None = None) -> str:
    root = root or REPO_ROOT
    records = load_catalog(root)
    lines: list[str] = [
        "# Generated by scripts/build-manifest.py. Do not edit by hand.",
        f"name: {q('kali-tools')}",
        f"version: {q(CATALOG_VERSION)}",
        f"description: {q('Portable Agent Skills catalog for authorized Kali Linux security testing.')}",
        f"license: {q(LICENSE_ID)}",
        f"format: {FORMAT_VERSION}",
        f"skill_count: {len(records)}",
        "supported_platforms: " + qlist(SUPPORTED_PLATFORMS),
        "platforms:",
    ]
    for platform in SUPPORTED_PLATFORMS:
        meta = PLATFORMS[platform]
        lines.append(f"  {platform}:")
        for key in ("status", "version", "validation", "result"):
            lines.append(f"    {key}: {q(meta[key])}")

    lines.append("skills:")
    for rec in sorted(records, key=lambda r: (r["id"] != "kali-tools", r["id"])):
        fm, rid = rec["fm"], rec["id"]
        meta = fm.get("metadata", {})
        rel = rec["path"].relative_to(root).as_posix()
        lines.append(f"  - id: {q(rid)}")
        lines.append(f"    name: {q(fm.get('name', ''))}")
        lines.append(f"    description: {q(str(fm.get('description', '')))}")
        lines.append(f"    path: {q(rel)}")
        lines.append(f"    category: {q(meta.get('category', ''))}")
        lines.append(f"    type: {q(meta.get('type', ''))}")
        lines.append(f"    status: {q(meta.get('status', ''))}")
        lines.append(f"    source: {q(meta.get('source', ''))}")
        lines.append(f"    aliases: {qlist(meta.get('aliases', []))}")
        lines.append(f"    dependencies: {qlist(meta.get('dependencies', []))}")
        lines.append(f"    format: {FORMAT_VERSION}")
        lines.append(f"    verification: {q(meta.get('verification', ''))}")
        if meta.get("executable"):
            lines.append(f"    executable: {qlist(meta['executable'])}")
        if meta.get("package"):
            lines.append(f"    package: {qlist(meta['package'])}")
        lines.append(f"    required_capabilities: {qlist(meta.get('capabilities', []))}")
        lines.append(f"    activation: {qlist(meta.get('activation', []))}")
        lines.append(f"    prerequisites: {qlist(meta.get('prerequisites', []))}")
        lines.append(f"    related_skills: {qlist(meta.get('related', []))}")
        lines.append(f"    supported_platforms: {qlist(SUPPORTED_PLATFORMS)}")

    workflows = sorted((root / "workflows").glob("*.md")) if (root / "workflows").is_dir() else []
    if workflows:
        lines.append("workflows:")
        for wf in workflows:
            fm, _ = parse_frontmatter(wf.read_text(encoding="utf-8"))
            lines.append(f"  - id: {q(wf.stem)}")
            lines.append(f"    path: {q(wf.relative_to(root).as_posix())}")
            lines.append(f"    description: {q(str(fm.get('description', '')))}")
            lines.append(f"    uses: {qlist(fm.get('uses', []) or [])}")

    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if manifest.yaml is out of date")
    args = parser.parse_args()

    try:
        content = build()
    except FrontmatterError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    manifest_path = REPO_ROOT / "manifest.yaml"
    if args.check:
        current = manifest_path.read_text(encoding="utf-8") if manifest_path.is_file() else ""
        if current != content:
            print("error: manifest.yaml is out of date; run scripts/build-manifest.py", file=sys.stderr)
            return 1
        # ensure our own reader agrees with the generated document
        parsed = parse_simple_yaml(content)
        if not isinstance(parsed.get("skills"), list) or not parsed.get("skills"):
            print("error: generated manifest failed self-parse", file=sys.stderr)
            return 1
        print(f"OK: manifest up to date ({len(parsed['skills'])} skills)")
        return 0

    manifest_path.write_text(content, encoding="utf-8")
    parsed = parse_simple_yaml(content)
    print(f"wrote manifest.yaml ({len(parsed.get('skills', []))} skills, version {CATALOG_VERSION})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
